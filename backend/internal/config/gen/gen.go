// Package gen renders .env.example and the doc tables from the config
// registry; output is deterministic (declaration order, no timestamps).
package gen

import (
	_ "embed"
	"fmt"
	"slices"
	"strings"

	"github.com/darthsoup/goblinftp/internal/config"
)

//go:embed env.tail.tmpl
var envTail string

// DocPages lists every file carrying confgen markers.
var DocPages = []string{
	"docs/configuration.md",
	"docs/logging.md",
	"docs/metrics.md",
	"docs/s3-staging.md",
	"docs/embedding.md",
}

const envHeader = `# GoblinFTP environment variables - generated by 'just confgen', documented in
# docs/configuration.md. Values are commented out and show the built-in default;
# docker compose loads this file via env_file, so an uncommented line is live.
`

// EnvExample renders .env.example: every registry key with an env form,
// grouped by section, plus the hand-written dev/testing tail.
func EnvExample() string {
	defaults := config.Defaults()
	var b strings.Builder
	b.WriteString(envHeader)

	lastSection := ""
	for i := range config.Registry {
		k := &config.Registry[i]
		if k.Env == "" {
			continue
		}
		if k.Section != lastSection {
			lastSection = k.Section
			b.WriteString("\n" + sectionRule(k.Section) + "\n")
		}
		b.WriteString("#" + k.Env + "=" + envValue(k, defaults) + "\n")
	}

	b.WriteString("\n" + strings.TrimRight(envTail, "\n") + "\n")
	return b.String()
}

func envValue(k *config.Key, defaults *config.Config) string {
	if k.Secret {
		return ""
	}
	return k.RenderDefault(defaults)
}

const (
	markerBegin = "<!-- confgen:begin "
	markerEnd   = "<!-- confgen:end -->"
)

// InjectTables replaces every `<!-- confgen:begin … --> … <!-- confgen:end -->`
// block with its rendered table; unbalanced or unknown markers are errors.
func InjectTables(doc string) (string, error) {
	lines := strings.Split(doc, "\n")
	var out []string
	for i := 0; i < len(lines); i++ {
		line := lines[i]
		trimmed := strings.TrimSpace(line)
		if !strings.HasPrefix(trimmed, markerBegin) {
			out = append(out, line)
			continue
		}

		spec := strings.TrimSuffix(strings.TrimPrefix(trimmed, markerBegin), " -->")
		table, err := renderMarker(spec)
		if err != nil {
			return "", err
		}

		endIdx := -1
		for j := i + 1; j < len(lines); j++ {
			if strings.TrimSpace(lines[j]) == markerEnd {
				endIdx = j
				break
			}
			if strings.HasPrefix(strings.TrimSpace(lines[j]), markerBegin) {
				return "", fmt.Errorf("confgen marker %q: nested begin before end", spec)
			}
		}
		if endIdx == -1 {
			return "", fmt.Errorf("confgen marker %q: missing end marker", spec)
		}

		out = append(out, line)
		out = append(out, strings.Split(table, "\n")...)
		out = append(out, lines[endIdx])
		i = endIdx
	}
	return strings.Join(out, "\n"), nil
}

func renderMarker(spec string) (string, error) {
	switch {
	case spec == "renamed-env-table":
		return renamedEnvTable(), nil
	case spec == "removed-keys-table":
		return removedKeysTable(), nil
	case strings.HasPrefix(spec, `env-table "`) && strings.HasSuffix(spec, `"`):
		section := strings.TrimSuffix(strings.TrimPrefix(spec, `env-table "`), `"`)
		return envTable(section)
	default:
		return "", fmt.Errorf("unknown confgen marker %q", spec)
	}
}

// renamedEnvTable renders the migration guide's rename map from the same data
// the runtime detection uses.
func renamedEnvTable() string {
	renamed := config.RenamedEnv()
	olds := make([]string, 0, len(renamed))
	for old := range renamed {
		olds = append(olds, old)
	}
	slices.Sort(olds)
	rows := []string{"| Old variable | New variable |", "|---|---|"}
	for _, old := range olds {
		rows = append(rows, "| `"+old+"` | `"+renamed[old]+"` |")
	}
	return strings.Join(rows, "\n")
}

func removedKeysTable() string {
	removed := config.RemovedEnv()
	names := make([]string, 0, len(removed))
	for name := range removed {
		names = append(names, name)
	}
	slices.Sort(names)
	rows := []string{"| Removed variable | Note |", "|---|---|"}
	for _, name := range names {
		rows = append(rows, "| `"+name+"` | "+escapePipes(removed[name])+" |")
	}
	return strings.Join(rows, "\n")
}

func envTable(section string) (string, error) {
	defaults := config.Defaults()
	rows := []string{"| Variable | Default | Description |", "|---|---|---|"}
	found := false
	for i := range config.Registry {
		k := &config.Registry[i]
		if k.Section != section || k.Env == "" {
			continue
		}
		found = true
		rows = append(rows, "| `"+k.Env+"` | "+defaultCell(k, defaults)+" | "+escapePipes(k.Doc)+" |")
	}
	if !found {
		return "", fmt.Errorf("confgen: no env keys in section %q", section)
	}
	return strings.Join(rows, "\n"), nil
}

func defaultCell(k *config.Key, defaults *config.Config) string {
	if k.AutoGenerated() {
		return "(auto-generated)"
	}
	if k.Secret {
		return "(none)"
	}
	if v := k.RenderDefault(defaults); v != "" {
		return "`" + v + "`"
	}
	return "(none)"
}

func escapePipes(s string) string { return strings.ReplaceAll(s, "|", `\|`) }

func sectionRule(title string) string {
	const width = 80
	prefix := "# ── " + title + " "
	if pad := width - len([]rune(prefix)); pad > 0 {
		return prefix + strings.Repeat("─", pad)
	}
	return prefix
}
